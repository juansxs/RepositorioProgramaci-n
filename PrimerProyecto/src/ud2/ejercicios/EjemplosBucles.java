package ud2.ejercicios;

public class EjemplosBucles {
    public static void main(String[] args) {
        int contador = -8;
        //Bucle de creo repeticiones
        while (contador >= 0) {
            System.out.println(contador);
        }


        while (contador < 0) {
            System.out.println(contador);
        }
    }

}
